// Regenerate after tools/prepare-geodata.ps1. Geometries are licensed separately
// from application code; see data/NOTICE.md. No API request or key is needed.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),input=path.resolve(process.argv[2]||path.join(root,'build/geodata-research/simplified'));
const mapping=JSON.parse(fs.readFileSync(path.join(root,'data/territory-mapping.json'),'utf8'));
const regions=JSON.parse(fs.readFileSync(path.join(root,'data/regions.json'),'utf8'));
const normalize=s=>s.toLowerCase().replace(/^м\.\s*/,'').replace(/\s+область$/,'').trim();
const byCode=new Map(mapping.entries.map(e=>[e.pcode,e]));
const seen=new Set(),apiSeen=new Set();
const project=([lon,lat])=>[+((lon-22)*Math.cos(48*Math.PI/180)).toFixed(5),+(53-lat).toFixed(5)];
const out={version:1,source:'OCHA Ukraine COD-AB v05 · CC BY 3.0 IGO',validOn:'2025-09-01'};
let vertices=0;
for(const [level,key,kind] of [[1,'states','State'],[2,'districts','District'],[3,'communities','Community']]){
 const data=JSON.parse(fs.readFileSync(path.join(input,'ukr_admin'+level+'.json'),'utf8'));
 out[key]=data.features.map(f=>{
  const p=f.properties,code=p['adm'+level+'_pcode'];if(seen.has(code))throw Error('Duplicate geometry '+code);seen.add(code);
  const oblast=regions.findIndex(r=>normalize(r.name)===normalize(p.adm1_name1));
  if(oblast<0)throw Error('Unknown oblast '+p.adm1_name1);
  const polygons=f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.type==='MultiPolygon'?f.geometry.coordinates:null;
  if(!polygons)throw Error('Invalid geometry '+code);
  const rings=polygons.flatMap(poly=>poly.map(r=>r.map(project)));vertices+=rings.reduce((n,r)=>n+r.length,0);
  const m=byCode.get(code);
  if(m){if(apiSeen.has(m.id))throw Error('Duplicate API binding '+m.id);apiSeen.add(m.id);if((m.geometryType||m.type)!==kind)throw Error('Type mismatch '+code);}
  return {code,oblast,kind,name:p['adm'+level+'_name1']+(level===2?' район':''),parentCode:p['adm'+(level-1)+'_pcode']||'',apiId:m?.id||'',apiName:m?.name||'',apiParent:m?.parent||'',rings};
 });
}
if(out.states.length!==27||out.districts.length!==139||out.communities.length!==1769||apiSeen.size!==mapping.entries.length)throw Error('Coverage changed; review source and mappings');
fs.writeFileSync(path.join(root,'web/territories.js'),'// Generated by tools/generate-details.js. OCHA / Kartographia, CC BY 3.0 IGO.\nwindow.AIRALERT_TERRITORIES = '+JSON.stringify(out)+';\n');
console.log(`Generated 27 oblasts, 139 districts, 1769 communities; ${apiSeen.size} API bindings, ${vertices} vertices.`);
